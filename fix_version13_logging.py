    "            loss = (loss_q8 + loss_q3) / cfg.grad_accum\n",
    "        \n",
    "        scaler.scale(loss).backward()\n",
    "        \n",
    "        if (step + 1) % cfg.grad_accum == 0:\n",
    "            scaler.unscale_(optimizer)\n",
