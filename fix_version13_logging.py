    "            optimizer.zero_grad()\n",
    "            scheduler.step(epoch + step / len(loader))\n",
    "        \n",
    "        total_loss += (loss_q8.item() + loss_q3.item())\n",
    "        \n",
    "        # Calculate approximate F1 for progress bar\n",
    "        with torch.no_grad():\n",
